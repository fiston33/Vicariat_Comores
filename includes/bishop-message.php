            <p class="eyebrow">Message de l'Évêque</p>
            <h2>Chers frères et sœurs en Christ</h2>
            <p class="bishop-quote">« Que la paix et la grâce de notre Seigneur Jésus-Christ soient avec vous tous. »</p>
            <div class="bishop-body">
                <p>En cette période particulière de notre vie ecclésiale et nationale, je souhaite adresser à chacun de vous un message d'espérance, d'unité et de confiance en Dieu. Malgré les défis auxquels nous faisons face dans nos familles, nos communautés et notre société, nous sommes appelés à demeurer fermes dans la foi et à témoigner de l'amour du Christ autour de nous.</p>
                <div class="bishop-more" id="bishopMore">
                    <p>L'Évangile nous rappelle que nous sommes tous frères et sœurs, appelés à vivre dans le respect mutuel, la solidarité et la réconciliation. Dans un monde marqué par les divisions, les difficultés économiques et les incertitudes, notre mission est d'être des artisans de paix, des témoins de la vérité et des serviteurs des plus vulnérables.</p>
                    <p>J'encourage toutes les familles à persévérer dans la prière, à transmettre les valeurs chrétiennes aux jeunes générations et à cultiver l'esprit de partage. J'invite également les jeunes à garder confiance en leur avenir, à développer leurs talents et à contribuer activement au développement de notre pays dans un esprit de responsabilité et de fraternité.</p>
                    <p>Je remercie les prêtres, les religieux, les religieuses, les catéchistes et tous les fidèles engagés dans la mission de l'Église pour leur dévouement et leur témoignage de foi.</p>
                    <p>Confions notre Vicariat Apostolique, notre nation et toutes nos familles à l'intercession de la Bienheureuse Vierge Marie. Que Dieu bénisse abondamment l'Archipel des Comores et chacun de ses habitants.</p>
